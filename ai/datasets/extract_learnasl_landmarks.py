"""
Extract one representative 21-landmark handshape per ASL letter and export
it as a JavaScript module for the Learn ASL page.

For every label we pick the *medoid* — the real dataset sample whose
landmarks are closest to all other samples of that letter — so the drawing
looks like an actual handshape instead of a blurry average.
"""
import json
import os
import sys

_AI_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # ai/
_PROJ_ROOT = os.path.dirname(_AI_ROOT)                                   # repo root
for _p in (_AI_ROOT, _PROJ_ROOT):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import numpy as np
import pandas as pd

from ai._paths import DATASET_CSV

OUT = os.path.join(_PROJ_ROOT, 'frontend', 'src', 'data', 'asl_landmarks.js')


def main():
    df = pd.read_csv(DATASET_CSV)
    xy = df.filter(regex='^x[0-9]+$|^y[0-9]+$').columns
    labels = sorted(set(df['folder']) - {'space'})

    entries = {}
    for label in labels:
        rows = df[df['folder'] == label][xy].to_numpy(dtype=np.float32)
        if len(rows) == 0:
            continue
        # medoid: sample with the smallest total distance to its class members
        mean = rows.mean(axis=0)
        dists = np.linalg.norm(rows - mean, axis=1)
        best = rows[int(np.argmin(dists))]
        pts = [[round(float(best[i]), 6), round(float(best[i + 1]), 6)] for i in range(0, len(best), 2)]
        entries[label] = pts

    module = (
        '// Auto-generated by ai/datasets/extract_learnasl_landmarks.py\n'
        '// Representative 21-landmark ({x,y}) handshape per ASL letter,\n'
        '// sourced from dataset/hand_keypoints.csv (medoid of each class).\n'
        'export const ASL_LANDMARKS = '
        + json.dumps(entries, indent=2)
        + '\n'
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(module)
    print(f'Wrote {len(entries)} letters -> {OUT}')


if __name__ == '__main__':
    main()